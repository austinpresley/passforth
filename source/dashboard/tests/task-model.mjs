import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync('lib/task-model.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { needsYou, unknownOwner, reportConcern, orderedTasks, taskGroup, taskLine, matchesTask, sourceLabel, unread } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const now = Date.parse('2026-10-17T20:00:00Z');
const task = { task_key: 'a', status: 'waiting', action_owner: 'user', created_at: '2026-10-17T10:00:00Z', updated_at: '2026-10-17T19:00:00Z', next_check_at: null };
assert.equal(needsYou(task), true);
for (const owner of ['dot', 'external', 'unknown', undefined]) assert.equal(needsYou({ ...task, action_owner: owner }), false);
for (const status of ['working', 'paused', 'scheduled', 'completed', 'cancelled']) assert.equal(needsYou({ ...task, status }), false);
assert.equal(unknownOwner({ ...task, action_owner: undefined }), true);
assert.equal(reportConcern(task, now), null);
for (const status of ['working', 'waiting', 'blocked']) {
  assert.equal(reportConcern({ ...task, status, updated_at: '2026-10-17T12:00:00Z' }, now), 'No report in over 6 hours');
}
assert.equal(reportConcern({ ...task, action_owner: 'external', next_check_at: '2026-10-17T19:30:00Z' }, now), 'Expected check-in is missing');
for (const status of ['completed', 'cancelled']) assert.equal(reportConcern({ ...task, status, next_check_at: '2026-10-01T00:00:00Z' }, now), null);
assert.equal(reportConcern({ ...task, status: 'paused', next_check_at: '2026-10-01T00:00:00Z' }, now), 'Expected check-in is missing');
assert.equal(reportConcern({ ...task, status: 'paused', updated_at: '2026-10-01T00:00:00Z' }, now), null);
assert.equal(reportConcern({ ...task, status: 'scheduled', next_check_at: '2026-10-20T00:00:00Z' }, now), null);
const newer = { ...task, task_key: 'b', created_at: '2026-10-17T11:00:00Z', updated_at: '2026-10-17T21:00:00Z' };
assert.deepEqual(orderedTasks([newer, task]).map(t => t.task_key), ['a', 'b']);
assert.deepEqual(orderedTasks([newer, { ...task, updated_at: '2026-10-17T22:00:00Z' }]).map(t => t.task_key), ['a', 'b']);
console.log('Task presentation checks passed: ownership, stale reports, terminal states, and stable ordering.');

assert.equal(taskGroup(task),'you');
assert.equal(taskGroup({...task,action_owner:'unknown'}),'unknown');
assert.equal(taskGroup({...task,action_owner:'external'}),'external');
assert.equal(taskGroup({...task,action_owner:'dot'}),'dot');
assert.equal(taskGroup({...task,status:'working',action_owner:'unknown'}),'reported');
assert.equal(taskGroup({...task,status:'scheduled'}),'scheduled');
assert.equal(taskGroup({...task,status:'paused'}),'later');
assert.equal(taskGroup({...task,status:'completed'}),'completed');
assert.equal(taskGroup({...task,status:'cancelled'}),'cancelled');
assert.equal(taskLine({...task,blocker:'Awaiting details, decision or fresh evidence; no dedicated check time is scheduled.',summary:'17 selects received. Fee unresolved.'}),'17 selects received. Fee unresolved.');
assert.equal(matchesTask({...task,title:'Example invoice',summary:'Rate unresolved',details:'Airfare excluded: $123.45.'},'invoice 123.45'),true);
assert.equal(matchesTask({...task,title:'Example invoice',summary:'Rate unresolved'},'invoice approved'),false);
assert.equal(sourceLabel({...task,source_url:'https://books.zoho.com/app/1#/invoices/2'}),'Review invoice');
assert.equal(sourceLabel({...task,source_url:'https://example.com',source_label:'Review draft'}),'Review draft');
assert.equal(unread({...task,attention_version:2,read_version:1}),true);
assert.equal(unread({...task,attention_version:2,read_version:2}),false);
assert.equal(reportConcern({...task,updated_at:'2026-10-17T19:59:00Z',progress_at:'2026-10-17T10:00:00Z'},now),'No report in over 6 hours');
console.log('Compact presentation checks passed: exclusive groups, useful context, evidence search, named links, unread state, and progress freshness.');

const models = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
assert.equal(models.inWorkView({...task, deadline:'2026-10-16'}, 'today', '2026-10-17'), true);
assert.equal(models.inWorkView({...task, deadline:'2026-10-16'}, 'upcoming', '2026-10-17'), false);
assert.equal(models.inWorkView({...task, planned_on:null}, 'anytime', '2026-10-17'), true);
assert.equal(models.inWorkView({...task, status:'paused'}, 'anytime', '2026-10-17'), false);
const planningJs = ts.transpileModule(readFileSync('lib/planning-model.ts', 'utf8').replace("from './task-model'", "from 'data:text/javascript;base64," + Buffer.from(js).toString('base64') + "'"), {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const planning = await import('data:text/javascript;base64,' + Buffer.from(planningJs).toString('base64'));
assert.deepEqual(planning.weekDays('2026-10-18'), ['2026-10-12','2026-10-13','2026-10-14','2026-10-15','2026-10-16','2026-10-17','2026-10-18']);
assert.equal(planning.labelMatches('studio/portraits client', 'studio'), true);
assert.equal(planning.labelMatches('studio/portraits', 'stud'), false);
assert.deepEqual(planning.labelTree(['studio/portraits','studio/lighting']),['studio','studio/lighting','studio/portraits']);
const timed={id:'a',task_key:'a',starts_at:'2026-10-17T12:00:00Z',duration_minutes:60,timezone:'America/New_York',version:1,archived:0};
assert.equal(planning.matchesView({...task,planned_on:null}, {...planning.emptyFilter,view:'today'}, '2026-10-17', [timed]), true);
assert.equal(planning.blocksOverlap(timed,{...timed,id:'b',starts_at:'2026-10-17T12:30:00Z'}),true);
assert.equal(planning.blocksOverlap(timed,{...timed,id:'b',starts_at:'2026-10-17T13:00:00Z'}),false);
console.log('Planning behavior checks passed: overdue deadlines, Anytime, week boundaries, nested labels, timed Today tasks and overlap detection.');
